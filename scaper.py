#!/usr/bin/env python3
import os
import json
from datetime import datetime

print("=" * 50)
print("News Scraper Running...")
print(f"Current directory: {os.getcwd()}")
print(f"Files here: {os.listdir('.')}")
print("=" * 50)

# داده تستی
NEWS_DATA = {
    "Fox News": [
        {"title": "Trump announces new policy", "link": "https://foxnews.com/1", "source": "Fox News"},
        {"title": "Breaking: White House update", "link": "https://foxnews.com/2", "source": "Fox News"},
    ],
    "ABC News": [
        {"title": "World news today", "link": "https://abcnews.com/1", "source": "ABC News"},
    ],
    "CBS News": [
        {"title": "Evening news recap", "link": "https://cbsnews.com/1", "source": "CBS News"},
    ],
    "The Jerusalem Post": [
        {"title": "Israel news update", "link": "https://jpost.com/1", "source": "Jerusalem Post"},
    ]
}

def create_html():
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    html = f'''<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8">
    <title>News Monitor - {timestamp}</title>
    <style>
        body {{ font-family: Arial, sans-serif; margin: 0; padding: 20px; background: #f4f4f4; }}
        .container {{ max-width: 900px; margin: auto; background: white; border-radius: 10px; padding: 20px; }}
        h1 {{ color: #1a1a2e; }}
        .news-item {{ margin: 15px 0; padding: 10px; border-left: 3px solid #007bff; background: #fafafa; }}
        .source {{ color: #007bff; font-weight: bold; }}
        .timestamp {{ color: #666; font-size: 12px; }}
        hr {{ margin: 20px 0; }}
    </style>
</head>
<body>
    <div class="container">
        <h1>📰 Global News Aggregator</h1>
        <p class="timestamp">Last updated: {timestamp}</p>
        <hr>
'''
    
    for source, articles in NEWS_DATA.items():
        html += f'<h2>{source}</h2>'
        for article in articles:
            html += f'''
        <div class="news-item">
            <a href="{article["link"]}" target="_blank">{article["title"]}</a>
            <div class="source">Source: {article["source"]}</div>
        </div>
'''
    
    html += '''
        <hr>
        <p style="color: #666; font-size: 12px;">Generated by GitHub Actions | Auto-updates every 30 minutes</p>
    </div>
</body>
</html>
'''
    return html

# ساخت پوشه‌ها
os.makedirs("output", exist_ok=True)
os.makedirs("backups", exist_ok=True)

# ذخیره HTML
html_content = create_html()
with open("output/index.html", "w", encoding="utf-8") as f:
    f.write(html_content)
print("✅ index.html created")

# ساخت MHTML
mhtml_content = f"""From: GitHub Actions
Subject: News Report
MIME-Version: 1.0
Content-Type: multipart/related; type="text/html"; boundary="boundary123"

--boundary123
Content-Type: text/html; charset="utf-8"
Content-Transfer-Encoding: 8bit

{html_content}
--boundary123--
"""

with open("output/news.mhtml", "w", encoding="utf-8") as f:
    f.write(mhtml_content)
print("✅ news.mhtml created")

# فایل وضعیت
status = {"timestamp": datetime.now().isoformat(), "sources": len(NEWS_DATA), "status": "success"}
with open("output/status.json", "w") as f:
    json.dump(status, f, indent=2)

print("=" * 50)
print("✅ All files created successfully!")
print(f"- output/index.html: {os.path.getsize('output/index.html')} bytes")
print(f"- output/news.mhtml: {os.path.getsize('output/news.mhtml')} bytes")
print("=" * 50)
